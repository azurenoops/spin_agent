// =============================================================================
// provenance.ts — Editor Suite provenance types (#940, #939, #1458, #1457)
//
// Phase 1 — Provenance field schema + user_modified span tracking
// Phase 2 — Streaming diff + citation badge types
// Phase 3 — QuoteAnchor + drift detection
// Phase 4 — Caption Registry
//
// All types are append-only and forward-compatible with legacy un-provenanced
// content (every consumer must treat absence of a ProvenanceSpan as graceful
// fallback — no badge, no error).
